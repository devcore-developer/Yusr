// extract-data.js
const fs = require('fs');

// 1. ضع ملف الـ HTML الأصلي الذي أرسلته لي سابقاً في جذر المشروع باسم original.html
const htmlFileName = 'original.html'; 
const htmlContent = fs.readFileSync(htmlFileName, 'utf8');

// 2. استخراج النص الموجود بين const DATA= و const TOOL_DATA=
const startIndex = htmlContent.indexOf('const DATA=') + 'const DATA='.length;
const endIndex = htmlContent.indexOf('const TOOL_DATA=', startIndex);
let jsonString = htmlContent.slice(startIndex, endIndex).trim();

// إزالة الفاصلة المنقوطة في النهاية إن وجدت
if (jsonString.endsWith(';')) {
  jsonString = jsonString.slice(0, -1);
}

try {
  // 3. تحويل النص إلى كائن جافاسكريبت
  const data = JSON.parse(jsonString);
  
  // 4. كتابة الكائن في ملف TypeScript جديد
  const tsContent = `// This file is auto-generated by extract-data.js\nexport const DATA = ${JSON.stringify(data, null, 2)};\n`;
  fs.writeFileSync('prisma/official-data.ts', tsContent);
  
  console.log('✅ تم إنشاء ملف prisma/official-data.ts بنجاح مع جميع الـ 597 شاهداً!');
  console.log(`📊 إجمالي الشواهد المستخرجة: ${data.evidence.length}`);
} catch (error) {
  console.error('❌ حدث خطأ أثناء تحويل البيانات:', error.message);
}